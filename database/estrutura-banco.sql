create table if not exists estacoes (
    id        bigint generated by default as identity primary key,
    nome      text not null,
    endereco  text
);

create table if not exists usuarios (
    id    bigint generated by default as identity primary key,
    nome  text not null
);

create table if not exists veiculos (
    id              bigint generated by default as identity primary key,
    usuario_id      bigint not null references usuarios(id),
    modelo          text not null,
    placa           text,
    capacidade_kwh  numeric(6,2)
);

create table if not exists tarifas (
    id         bigint generated by default as identity primary key,
    nome       text not null,
    preco_kwh  numeric(6,2) not null check (preco_kwh >= 0)
);

create table if not exists carregadores (
    id           bigint generated by default as identity primary key,
    id_estacao   bigint not null references estacoes(id),
    status       text not null check (status in ('Livre', 'Ocupado')),
    potencia_kw  numeric(7,2) not null check (potencia_kw between 0 and 400)
);

-- Atenção: "energia_solar_kW" e "energia_kWh" usam aspas porque têm letras maiúsculas.
-- Sem as aspas, o PostgreSQL criaria energia_solar_kw e o código Python não encontraria a coluna.
create table if not exists estado_energetico (
    id                      bigint generated by default as identity primary key,
    created_at              timestamptz not null default now(),
    estacao_id              bigint not null references estacoes(id),
    "energia_solar_kW"      numeric(8,2) not null check ("energia_solar_kW" >= 0),
    energia_rede_kw         numeric(8,2) not null check (energia_rede_kw >= 0),
    demanda_kw              numeric(8,2) not null check (demanda_kw >= 0),
    potencia_disponivel_kw  numeric(8,2) not null check (potencia_disponivel_kw >= 0),
    bateria_percentual      numeric(5,2) not null check (bateria_percentual between 0 and 100),
    status_gerenciamento    text not null
);

create table if not exists comandos_de_automacao (
    id                    bigint generated by default as identity primary key,
    created_at            timestamptz not null default now(),
    tipo_comando          text not null check (tipo_comando in ('REDUZIR', 'AUMENTAR', 'MANTER')),
    potencia_anterior_kw  numeric(7,2) not null,
    carregador_id         bigint not null references carregadores(id),
    potencia_nova_kw      numeric(7,2) not null,
    motivo                text,
    executado             boolean not null default false,
    executado_em          timestamptz
);

create table if not exists sessoes_carregamento (
    id             bigint generated by default as identity primary key,
    created_at     timestamptz not null default now(),
    estacao_id     bigint not null references estacoes(id),
    carregador_id  bigint not null references carregadores(id),
    usuario_id     bigint not null references usuarios(id),
    veiculo_id     bigint not null references veiculos(id),
    tarifa_id      bigint not null references tarifas(id),
    tempo_inicial  timestamptz,
    tempo_final    timestamptz,
    "energia_kWh"  numeric(10,3),
    custo          numeric(10,2),
    status         text
);

-- Índice que acelera a busca de comandos pendentes por carregador
create index if not exists idx_comandos_pendentes
    on comandos_de_automacao (carregador_id) where executado = false;

